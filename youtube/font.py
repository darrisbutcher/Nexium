def bitmap(text, gap=1):
    """Return 2D list of 0/1 for text (7 rows tall), letter spacing `gap` pixels."""
    cols = []
    for i, ch in enumerate(text.upper()):
        rows = G[ch]
        w = len(rows[0])
        for x in range(w):
            cols.append([1 if rows[y][x] == '#' else 0 for y in range(7)])
        if i < len(text) - 1:
            for _ in range(gap): cols.append([0]*7)
    return [[c[y] for c in cols] for y in range(7)]
